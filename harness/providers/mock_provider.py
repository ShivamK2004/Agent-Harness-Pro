"""Deterministic offline provider for tests, demos, and setup validation."""
from __future__ import annotations
import re
from .base import BaseProvider

class MockProvider(BaseProvider):
    name = "mock"
    model = "deterministic-mock-v1"

    def generate(self, system_prompt: str, user_prompt: str) -> str:
        role = system_prompt.lower()
        if "you are the planner" in role:
            return '{"goal":"Answer the user using available evidence","steps":["Retrieve relevant local information","Prepare a concise grounded response","Verify evidence and citations"],"tools":["knowledge_search"],"risk":"low"}'
        if "you are the verifier" in role:
            return '{"status":"reviewed","supported_points":[],"unsupported_points":[],"citation_check":"No unsupported factual claims were intentionally added by mock mode.","risk_flags":[],"recommendation":"The response is a deterministic mock demonstration; validate it with a real provider for meaningful quality review."}'
        if "you are the researcher" in role:
            return "Research completed using the supplied local knowledge snippets."
        if "you are the executor" in role:
            question_match = re.search(r"(?:user task|question|task)\s*[:\n]\s*(.+)", user_prompt, re.I)
            question = question_match.group(1).strip() if question_match else "the request"
            context_match = re.search(r"retrieved evidence\s*[:\n]+(.+?)(?:\n\nTool outputs:|$)", user_prompt, re.I | re.S)
            context = context_match.group(1).strip() if context_match else "No local evidence was retrieved."
            calculator_result = re.search(r"'result':\s*'([^']+)'", user_prompt)
            if calculator_result:
                return (f"The calculated result is {calculator_result.group(1)}. "
                        "This result was produced by the restricted calculator tool in the local harness. "
                        "Mock mode is being used for workflow testing; switch to Gemini or Ollama for an LLM-generated explanation.")
            if "no local evidence" in context.lower() or "no matching" in context.lower():
                return (f"I can demonstrate the workflow for '{question}', but Mock mode does not use a live language model. "
                        "No matching local knowledge was retrieved, so I cannot provide a source-grounded factual answer. "
                        "Configure Gemini or Ollama for natural-language responses.")
            return (f"Here is a mock, evidence-aware response to: {question}\n\n"
                    f"The local knowledge base returned the following evidence:\n{context}\n\n"
                    "This output is generated by Mock mode for interface and pipeline testing. "
                    "Switch to Gemini or Ollama for an actual LLM-generated answer.")
        return "Mock provider is active. Configure Gemini or Ollama for model-generated responses."

    def health(self) -> dict:
        return {"provider": self.name, "model": self.model, "configured": True, "offline": True}
